// Generates netlify/functions/templates.gen.mjs from netlify/functions/templates/*.html.
// Netlify bundles each function into a single CJS file, so import.meta.url and sibling
// file reads break at runtime; inlining the templates keeps the bundle self-contained.
// Regenerated automatically by the prebuild step (npm run build).
import { readFileSync, writeFileSync } from 'node:fs';

const files = [
  'preview-credentials-24h.html',
  'preview-credentials-30d.html',
  'account-welcome.html',
];

let out = '// Generated by scripts/gen-templates.mjs from netlify/functions/templates/ — do not edit by hand.\n';
out += '// Regenerated automatically before every build (npm prebuild).\nexport const TEMPLATES = {\n';
for (const f of files) {
  out += `  ${JSON.stringify(f)}: ${JSON.stringify(readFileSync(new URL(`../templates/${f}`, import.meta.url), 'utf8'))},\n`;
}
out += '};\n';
writeFileSync(new URL('../templates.gen.mjs', import.meta.url), out);
console.log('wrote netlify/functions/templates.gen.mjs');
